/// 给豆包那类看图说话模型用的提示词。他拍单词表 → 发这段 → 把结果原样粘回录入页，
/// 所以这里的输出格式必须和 `parsePastedRows` 吃的五个字段严格对齐，
/// 改任何一边都要改另一边（test/protocol_test.dart 拿这段里的示例行当输入测）。
const String kAiWordPrompt = '''
我给你一张英语课本单词表的 photo。把里面的单词逐条整理出来，只输出结果本身，不要编号、不要表格、不要 Markdown、不要任何解释或前后缀。

一行一条，格式固定，用竖线 | 分隔 5 个字段，顺序不能变、不能少、不能加字段：

单词|音标|释义|例句|音节拆分

规则：
1. 单词：照片里的原形。除专有名词外全部小写。
2. 音标：英式 IPA，用斜杠包起来，例 /ʌmˈbrelə/。重音符号用 ˈ，长音用 ː，中央元音用 ə。不要用英文撇号、英文冒号这些替身字符 —— 设备字库认不出来，会显示成空白。
3. 释义：中文，带词性缩写，例 n. 雨伞。多个词性用英文分号 ; 分隔。控制在 20 个字以内，不要用带圈数字这类生僻符号。
4. 例句：一句简短英文，5 到 10 个词，能看出这个词怎么用，句末带句号。
5. 音节拆分：按读音音节用 - 分开，例 um-brel-la。单音节词原样写。这个字段里除了字母和 - 不要有别的字符。
6. 除分隔符外，全文任何地方都不能再出现 |，例句里也不能换行。
7. 长度上限（超了设备会被直接截断，不报错）：单词不超过 60 个字母；音标加音节合计不超过 93 个字符；释义不超过 60 个汉字；例句不超过 280 个字符。
8. 照片里有几行就出几条，按课本顺序，不要漏，也不要自己加词。照片里已经给了中文释义的，照抄课本那份，不要用你自己的。
9. 看不清的条目：保留这一行，把释义写成 （照片不清），其余字段留空但保留 |。

示例（假设照片里有 umbrella 和 cold 两个词）：
umbrella|/ʌmˈbrelə/|n. 雨伞|I take an umbrella when it rains.|um-brel-la
cold|/kəʊld/|adj. 寒冷的; n. 感冒|It is cold outside today.|cold
''';
